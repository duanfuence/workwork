#!/usr/bin/env bash
# Выкладка собранного сайта (dist/) на хостинг по SSH (D-034, D-035; инструкция — docs/DEPLOY.md).
#
# Запускается из .github/workflows/deploy.yml после проверок; можно запустить и локально с теми же переменными
# (список — в scripts/deploy-lib.sh). Дополнительно: DIST_DIR — папка сборки, по умолчанию dist; SITE_URL —
# адрес сайта для проверки после выкладки (обязателен).
#
# Порядок и статусы:
#   1. настройки, точный путь, полнота сборки — до подключения к серверу;
#   2. вход и папка сайта (только чтение);
#   3. резервная копия (ошибка — остановка; содержимое не менялось с прошлой копии — она и используется);
#   4. копирование в три этапа: статус copying, после — copied;
#   5. проверка сайта (scripts/check-site.sh): главная по SITE_URL байт в байт как в сборке;
#   6. только если проверка прошла — статус verified: эта версия становится последней хорошей, и следующая
#      резервная копия (перед следующей операцией) будет отмечена как проверенная.
# Шаги 4–6 связаны токеном, который не покидает этот процесс: отметить версию проверенной в обход проверки
# сайта нельзя. Сбой на любом шаге — выход с ошибкой, статус verified не ставится.
set -euo pipefail

here=$(dirname "${BASH_SOURCE[0]}")
# shellcheck source=scripts/deploy-lib.sh
source "$here/deploy-lib.sh"

DIST_DIR="${DIST_DIR:-dist}"

check_settings
[[ -n "${SITE_URL:-}" ]] ||
  fail 'Не задан SITE_URL — без проверки сайта выкладка не может быть отмечена проверенной. Остановлено до подключения к серверу.'

# Защита от пустой выкладки: без этих файлов сборка неполная, и удаление лишнего стёрло бы рабочий сайт.
for file in index.html 404.html .htaccess robots.txt sitemap.xml; do
  [[ -s "$DIST_DIR/$file" ]] || fail "В $DIST_DIR нет $file — выкладка остановлена до подключения к серверу."
done
pages=$(find "$DIST_DIR" -name index.html -type f | wc -l)
((pages >= 2)) || fail "В $DIST_DIR всего $pages страниц — выкладка остановлена до подключения к серверу."
echo "Сборка: $pages страниц, $(find "$DIST_DIR" -type f | wc -l) файлов."

setup_ssh
preflight

# Метка копии — коммит, который выкладывается (первые 7 знаков), или «manual» при запуске вне GitHub.
label=manual
[[ "${GITHUB_SHA:-}" =~ ^[0-9a-f]{40}$ ]] && label="${GITHUB_SHA:0:7}"
make_backup "$label"

token=$(new_token)
transfer "$DIST_DIR" "$token"
echo 'Копирование завершено. Проверка сайта…'

if ! bash "$here/check-site.sh" "$DIST_DIR/index.html"; then
  good=$(last_good)
  fail "Проверка сайта не прошла: файлы выложены, но эта версия НЕ отмечена как проверенная. Последняя проверенная версия — ${good:-пока нет}${good:+ (Actions → Restore, last-good)}. Что делать — docs/DEPLOY.md, «Если что-то не так»."
fi
code=0
remote verify "$token" || code=$?
[[ $code -ne 6 ]] ||
  fail 'Сайт прошёл проверку, но SHA-256 папки сайта на сервере для записи статуса вычислить не удалось (sha256sum) — версия не считается проверенной, последняя хорошая версия не изменилась.'
[[ $code -eq 0 ]] ||
  fail 'Сайт прошёл проверку, но статус «проверена» записать не удалось — версия не считается проверенной. Запустите выкладку ещё раз: копирование, проверка и запись статуса повторятся.'
echo 'Готово: сайт выложен и прошёл проверку — эта версия отмечена как последняя проверенная.'
