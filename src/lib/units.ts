/**
 * Словесные формы единиц измерения для вспомогательных технологий.
 *
 * Рядом с полем видно сокращение («мм»), но скринридер прочитал бы его по буквам или пропустил.
 * Поэтому сокращение скрыто от озвучивания, а в подпись поля добавляется невидимый текст
 * « (в миллиметрах)» — он входит в доступное имя поля и озвучивается один раз.
 */
const spokenUnits = {
  м: 'в метрах',
  см: 'в сантиметрах',
  мм: 'в миллиметрах',
  'м²': 'в квадратных метрах',
  л: 'в литрах',
  кг: 'в килограммах',
  '%': 'в процентах',
  '₽': 'в рублях',
  'шт.': 'в штуках',
  'м²/л': 'в квадратных метрах на литр',
  'кг/м²': 'в килограммах на квадратный метр',
} as const satisfies Record<string, string>;

export type Unit = keyof typeof spokenUnits;

export function isKnownUnit(unit: string): unit is Unit {
  return Object.hasOwn(spokenUnits, unit);
}

/** Словесная форма единицы. Неизвестная единица — ошибка сборки, а не молчаливый пропуск. */
export function spokenUnit(unit: string): string {
  if (!isKnownUnit(unit)) {
    throw new Error(`Нет словесной формы для единицы «${unit}» (src/lib/units.ts)`);
  }
  return spokenUnits[unit];
}
